#!/usr/bin/env python3
# Gera src/icone_freedoom.c (ícone do app Freedoom).
#   python3 tools/icone_freedoom.py c > src/icone_freedoom.c
#   python3 tools/icone_freedoom.py png previa.png
import sys, zlib, struct
# '#' = cheio, '+' = meio-tom (alpha), '.' = vazio. 24x24, ampliado 2x = 48x48.
ARTE = """
........................
........................
........................
........................
........................
....................+...
..................+.#.+.
..##############+..###..
.################.#####.
.+++++++++++++++#..###..
.################.+.#.+.
.#######+...........+...
.######.##..............
.######..#..............
.######.##..............
.#######................
..######................
..######................
..######................
..#####+................
........................
........................
........................
........................
"""
linhas = [l for l in ARTE.strip("\n").split("\n")]
assert all(len(l) == 24 for l in linhas) and len(linhas) == 24, [len(l) for l in linhas]
val = {'#': 255, '+': 150, '.': 0}
ESC = 2
px = [[val[c] for c in l for _ in range(ESC)] for l in linhas for _ in range(ESC)]
N = 24 * ESC
if sys.argv[1] == "png":
    raw = b"".join(b"\x00" + bytes(v for a in row for v in (a, a, a)) for row in px)
    # fundo marrom como o botão, para ver o contraste
    raw = b"".join(b"\x00" + bytes(v for a in row for v in (
        int(0x6d + (255 - 0x6d) * a / 255), int(0x4c + (255 - 0x4c) * a / 255), int(0x41 + (255 - 0x41) * a / 255))) for row in px)
    def chunk(t, d): return struct.pack(">I", len(d)) + t + d + struct.pack(">I", zlib.crc32(t + d) & 0xffffffff)
    png = b"\x89PNG\r\n\x1a\n" + chunk(b"IHDR", struct.pack(">IIBBBBB", N, N, 8, 2, 0, 0, 0)) + chunk(b"IDAT", zlib.compress(raw)) + chunk(b"IEND", b"")
    open(sys.argv[2], "wb").write(png)
else:
    dados = ",\n    ".join(", ".join(f"0x{v:02x}" for v in row) for row in px)
    print(f"""/* Ícone do app Freedoom: pistola com o clarão do tiro, em pixel art (desenho original, 48x48,
 * só transparência; a cor vem do estilo img_recolor). Gerado por tools/icone_freedoom.py. */
#include "lvgl.h"

static const uint8_t k_dados[] = {{
    {dados}
}};

const lv_img_dsc_t icone_freedoom = {{
    .header = {{.cf = LV_IMG_CF_ALPHA_8BIT, .always_zero = 0, .reserved = 0, .w = {N}, .h = {N}}},
    .data_size = sizeof(k_dados),
    .data = k_dados,
}};""")
